/**
 * Get the full template for a jurisdiction
 */
export function getJurisdictionTemplate(jurisdiction: string): string {
  const normalized = jurisdiction.toLowerCase();

  if (normalized.includes('india')) return INDIA_TEMPLATE;
  if (normalized.includes('ireland')) return IRELAND_TEMPLATE;
  if (normalized.includes('delaware')) return USA_DELAWARE_TEMPLATE;
  if (
    normalized.includes('uk') ||
    normalized.includes('united kingdom') ||
    normalized.includes('england') ||
    normalized.includes('britain')
  ) {
    return UK_TEMPLATE;
  }

  // Default to Ireland
  return IRELAND_TEMPLATE;
}
